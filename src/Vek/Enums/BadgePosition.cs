namespace Vek;

/// <summary>
/// A logical corner where a badge can be placed relative to its content.
/// </summary>
public enum BadgePosition
{
    /// <summary>
    /// Places the badge at the top end of its content.
    /// </summary>
    TopEnd,

    /// <summary>
    /// Places the badge at the top start of its content.
    /// </summary>
    TopStart,

    /// <summary>
    /// Places the badge at the bottom end of its content.
    /// </summary>
    BottomEnd,

    /// <summary>
    /// Places the badge at the bottom start of its content.
    /// </summary>
    BottomStart,
}
