namespace Vek
{
    /// <summary>
    /// Controls when a slider's value label is visible.
    /// </summary>
    public enum SliderValueLabelDisplay
    {
        /// <summary>
        /// Never displays the value label.
        /// </summary>
        Never,

        /// <summary>
        /// Displays the value label while the slider is hovered or keyboard-focused.
        /// </summary>
        OnHover,

        /// <summary>
        /// Always displays the value label.
        /// </summary>
        Always
    }
}
